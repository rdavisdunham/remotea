// Run from the repository root after adding settings controls or preference fields.
const fs = require('fs');
const ts = require('typescript');

const directory = 'src/renderer/components/Settings/';
const sections = {
  General: 'GeneralSettings',
  Hosts: 'RemoteHostsSettings',
  Sidebar: 'SidebarSettings',
  Workspace: 'WorkspaceSettings',
  Terminal: 'TerminalSettings',
  Prompts: 'PromptSettings',
  Notifications: 'NotificationSettings',
  Browser: 'BrowserSettings',
  Profiles: 'QuickLaunchSettings',
  Shortcuts: 'KeyboardSettings',
  Remote: 'RemoteConsoleSettings',
  Changelog: 'ChangelogSettings',
  Help: 'HelpSettings',
  Agents: 'AgentIntegrationSettings',
};
const terms = {};
for (const [section, file] of Object.entries(sections)) {
  const source = fs.readFileSync(`${directory}${file}.tsx`, 'utf8');
  const translations = source.matchAll(/t\(\s*'([^']+)'(?:,\s*'((?:\\.|[^'])*)')?/g);
  terms[section] = [...translations].map(match => ({
    key: match[1],
    label: match[2] || match[1],
  }));
}

const source = ts.createSourceFile(
  'settings-slice.ts',
  fs.readFileSync('src/renderer/store/settings-slice.ts', 'utf8'),
  ts.ScriptTarget.Latest,
  true,
);
const fields = {};
const preferenceInterface = /^(Appearance|Sidebar|Workspace|Terminal|Notification|Browser|Prompt|Keyboard)Prefs$/;
for (const node of source.statements) {
  if (!ts.isInterfaceDeclaration(node) || !preferenceInterface.test(node.name.text)) continue;
  fields[node.name.text] = node.members
    .filter(ts.isPropertySignature)
    .map(member => member.name.getText(source));
}

const generated = [
  '// Generated by scripts/generate-settings-search-index.cjs. Persisted IDs remain unchanged.',
  `export const SETTINGS_SEARCH_TERMS = ${JSON.stringify(terms, null, 2)} as const;`,
  `export const PREFERENCE_FIELDS = ${JSON.stringify(fields, null, 2)} as const;`,
  '',
].join('\n');
fs.writeFileSync(`${directory}settings-search-index.ts`, generated);
